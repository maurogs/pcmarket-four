  filter = FilterDefinition.find_or_initialize_by(key: attributes[:key])
  filter.assign_attributes(
    names: attributes[:names],
    input_type: attributes.fetch(:input, :checkbox),
    position: index + 1,
    active: true
  )
  filter.save!

  attributes[:options].each_with_index do |value, option_index|
    option = FilterOption.where(filter_definition: filter)
                         .find_by("lower(value) = ?", value.downcase)
    option ||= FilterOption.new(filter_definition: filter)
    option.value = value
    option.labels = filter_option_labels(value, filter_vocabulary)
    option.position = option_index + 1
    option.save!
  end

  attributes[:categories].each do |category_slug|
    category = Category.find_by!(slug: category_slug)
    category_filter = CategoryFilter.find_or_initialize_by(
      category: category, filter_definition: filter
    )
    category_filter.position = index + 1
    category_filter.save!
  end
